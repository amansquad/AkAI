// Regenerates KeyboardData.kt from the web keyboard's keyboard-data.ts, so the
// native keyboard and the web one never disagree about the Amharic letters.
// Run from the repo root:  node native_keyboard/tools/gen-data.mjs
import fs from 'node:fs';

const src = fs.readFileSync('src/components/keyboard-data.ts', 'utf8');

function grab(name) {
  let start = src.indexOf(`export const ${name}`);
  if (start < 0) start = src.indexOf(`const ${name}`);
  if (start < 0) throw new Error(`missing ${name}`);
  const eq = src.indexOf('=', start);
  // The initialiser ends at the first closing bracket followed by ";".
  const m = /[\]}];[ \t]*(\r?\n|$)/.exec(src.slice(eq));
  const end = eq + m.index + 1;
  // Drop TypeScript casts such as "[] as string[]" so it evaluates as plain JS.
  const body = src.slice(eq + 1, end).replace(/\s+as\s+[\w[\]]+/g, '');
  return new Function(`return (${body})`)();
}

// Kotlin treats "$" in a string as a template, so it has to be escaped.
const q = (s) => JSON.stringify(s).split('$').join('\\$');
const rows = (r) => `listOf(${r.map(x => `listOf(${x.map(c => q(c)).join(', ')})`).join(',\n        ')})`;
const map = (m) => `mapOf(\n${Object.entries(m).map(([k, v]) => `        ${q(k)} to listOf(${v.map(c => q(c)).join(', ')})`).join(',\n')}\n    )`;

const gifSrc = fs.readFileSync('src/components/giphy-catalog.ts', 'utf8');
function grabGifs() {
  const start = gifSrc.indexOf('const CATALOG');
  const eq = gifSrc.indexOf('=', start);
  const m = /\n\];/.exec(gifSrc.slice(eq));
  return new Function(`return (${gifSrc.slice(eq + 1, eq + m.index + 2)})`)();
}

// Letter rows only: the control keys are laid out by Layouts.kt itself.
const letterRows = (name) => grab(name).slice(0, 3).map(r => r.filter(k => k.length === 1));
const layoutMap = () => 'mapOf(\n' + ['DVORAK', 'AZERTY', 'COLEMAK', 'QWERTZ'].map(n =>
  `        ${q(n.toLowerCase())} to ${rows(letterRows(n + '_ROWS'))}`).join(',\n') + '\n    )';

const gifs = grabGifs().map(g =>
  `        Gif(${q(g.id)}, ${q(g.t)}, ${q(g.c)}, ${q(g.k)})`).join(',\n');

const out = `// GENERATED by tools/gen-data.mjs from src/components/keyboard-data.ts. Do not edit by hand.
package com.akai.nativekb

object KeyboardData {
    val amharicRows: List<List<String>> = ${rows(grab('AMHARIC_ROWS'))}

    val amharicFrequencyRows: List<List<String>> = ${rows(grab('AMHARIC_FREQUENCY_ROWS'))}

    /** Each consonant's whole vowel family; a long press shows it. */
    val amharicVowels: Map<String, List<String>> = ${map(grab('AMHARIC_VOWELS'))}

    /** Long-press alternates on the English board. */
    val englishAlternates: Map<String, List<String>> = ${map(grab('LONG_PRESS_ALTERNATES'))}

    val suggestionsEn: Map<String, List<String>> = ${map(grab('ENGLISH_SUGGESTIONS'))}
    val suggestionsAm: Map<String, List<String>> = ${map(grab('AMHARIC_SUGGESTIONS'))}
    val nextWordEn: Map<String, List<String>> = ${map(grab('NEXT_WORD_EN'))}
    val nextWordAm: Map<String, List<String>> = ${map(grab('NEXT_WORD_AM'))}

    /** Letter rows of the other English layouts; QWERTY is built in Layouts.kt. */
    val englishLayouts: Map<String, List<List<String>>> = ${layoutMap()}

    class Gif(val id: String, val title: String, val category: String, val keywords: String)
    val gifs: List<Gif> = listOf(
${gifs}
    )

    class StickerSet(val name: String, val icon: String, val stickers: List<String>)
    /** The web keyboard's sticker sets (its "Recent" set is kept on the phone instead). */
    val stickerSets: List<StickerSet> = listOf(
${grab('STICKER_CATEGORIES').filter(c => c.stickers.length).map(c =>
  `        StickerSet(${q(c.name)}, ${q(c.icon)}, listOf(${[...new Set(c.stickers)].map(q).join(', ')}))`).join(',\n')}
    )

    /** Word of the day, shown in the empty suggestion strip: word to meaning. */
    val wordOfTheDayEn: List<Pair<String, String>> = listOf(${grab('WORD_OF_THE_DAY_EN').map(w => `${q(w.word)} to ${q(w.definition)}`).join(', ')})
    val wordOfTheDayAm: List<Pair<String, String>> = listOf(${grab('WORD_OF_THE_DAY_AM').map(w => `${q(w.word)} to ${q(w.definition)}`).join(', ')})

    val ethiopicNumerals: List<String> = listOf(${grab('ETHIOPIAN_NUM_ROW_1').map(c => q(c)).join(', ')})
    val ethiopicPunctuation: List<String> = listOf(${grab('ETHIOPIAN_SYM_ROW').map(c => q(c)).join(', ')})
}
`;
fs.writeFileSync('native_keyboard/app/src/main/java/com/akai/nativekb/KeyboardData.kt', out);
console.log('wrote KeyboardData.kt');
