// Regenerates KeyboardData.kt from the web keyboard's keyboard-data.ts, so the
// native keyboard and the web one never disagree about the Amharic letters.
// Run from the repo root:  node native_keyboard/tools/gen-data.mjs
import fs from 'node:fs';

const src = fs.readFileSync('src/components/keyboard-data.ts', 'utf8');

function grab(name) {
  const start = src.indexOf(`export const ${name}`);
  if (start < 0) throw new Error(`missing ${name}`);
  const eq = src.indexOf('=', start);
  // The initialiser ends at the first closing bracket followed by ";".
  const m = /[\]}];[ \t]*(\r?\n|$)/.exec(src.slice(eq));
  const end = eq + m.index + 1;
  return new Function(`return (${src.slice(eq + 1, end)})`)();
}

// Kotlin treats "$" in a string as a template, so it has to be escaped.
const q = (s) => JSON.stringify(s).split('$').join('\\$');
const rows = (r) => `listOf(${r.map(x => `listOf(${x.map(c => q(c)).join(', ')})`).join(',\n        ')})`;
const map = (m) => `mapOf(\n${Object.entries(m).map(([k, v]) => `        ${q(k)} to listOf(${v.map(c => q(c)).join(', ')})`).join(',\n')}\n    )`;

const out = `// GENERATED by tools/gen-data.mjs from src/components/keyboard-data.ts. Do not edit by hand.
package com.akai.nativekb

object KeyboardData {
    val amharicRows: List<List<String>> = ${rows(grab('AMHARIC_ROWS'))}

    val amharicFrequencyRows: List<List<String>> = ${rows(grab('AMHARIC_FREQUENCY_ROWS'))}

    /** Each consonant's whole vowel family; a long press shows it. */
    val amharicVowels: Map<String, List<String>> = ${map(grab('AMHARIC_VOWELS'))}

    /** Long-press alternates on the English board. */
    val englishAlternates: Map<String, List<String>> = ${map(grab('LONG_PRESS_ALTERNATES'))}

    val ethiopicNumerals: List<String> = listOf(${grab('ETHIOPIAN_NUM_ROW_1').map(c => q(c)).join(', ')})
    val ethiopicPunctuation: List<String> = listOf(${grab('ETHIOPIAN_SYM_ROW').map(c => q(c)).join(', ')})
}
`;
fs.writeFileSync('native_keyboard/app/src/main/java/com/akai/nativekb/KeyboardData.kt', out);
console.log('wrote KeyboardData.kt');
