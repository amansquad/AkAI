// Generates FootballStyles.kt (every club's kit colours and motif name) from the
// Flutter app's football_live_theme.dart.
// Run from the repo root:  node native_keyboard/tools/gen-football.mjs
import fs from 'node:fs';

const src = fs.readFileSync('flutter_app/lib/app/theme/football_live_theme.dart', 'utf8');
const re = /'(\w+)':\s*TeamStyle\(\s*Color\(0x([0-9A-Fa-f]{8})\),\s*Color\(0x([0-9A-Fa-f]{8})\),\s*'(\w+)'\s*\)/g;
const rows = [];
let m;
while ((m = re.exec(src))) rows.push(`        "${m[1]}" to TeamStyle(0x${m[2].toUpperCase()}.toInt(), 0x${m[3].toUpperCase()}.toInt(), "${m[4]}")`);

fs.writeFileSync('native_keyboard/app/src/main/java/com/akai/nativekb/FootballStyles.kt',
`// GENERATED by tools/gen-football.mjs from the Flutter app. Do not edit by hand.
package com.akai.nativekb

class TeamStyle(val primary: Int, val secondary: Int, val motif: String)

object FootballStyles {
    val all: Map<String, TeamStyle> = mapOf(
${rows.join(',\n')}
    )
}
`);
console.log(`wrote FootballStyles.kt with ${rows.length} clubs`);
