// Regenerates EmojiData.kt from the unicode-emoji-json package's data-by-group.json,
// so the emoji tab carries the whole Unicode set in the standard order.
//   npm pack unicode-emoji-json && tar xzf unicode-emoji-json-*.tgz
//   node native_keyboard/tools/gen-emoji.mjs package/data-by-group.json
// Emoji newer than MAX_VERSION are left out; the phone also hides any its font can't draw.
import fs from 'node:fs';

const MAX_VERSION = 15.1;
const file = process.argv[2];
if (!file) throw new Error('usage: node gen-emoji.mjs <path to data-by-group.json>');
const groups = JSON.parse(fs.readFileSync(file, 'utf8'));

const meta = {
  smileys_emotion: ['😀', 'Smileys'],
  people_body: ['👋', 'People'],
  animals_nature: ['🐻', 'Animals and nature'],
  food_drink: ['🍔', 'Food and drink'],
  travel_places: ['✈️', 'Travel and places'],
  activities: ['⚽', 'Activities'],
  objects: ['💡', 'Objects'],
  symbols: ['❤️', 'Symbols'],
  flags: ['🏁', 'Flags'],
};

// Kotlin treats "$" in a string as a template, so it has to be escaped.
const q = (s) => JSON.stringify(s).split('$').join('\\$');
const cps = (s) => [...s].filter((c) => c !== '️');

const toneable = [];
const cats = [];
const names = [];
for (const g of groups) {
  const m = meta[g.slug];
  if (!m) continue;
  let list = g.emojis.filter((e) => parseFloat(e.emoji_version) <= MAX_VERSION);
  // Home first.
  if (g.slug === 'flags') {
    const et = list.findIndex((e) => e.emoji === '🇪🇹');
    if (et > 0) list = [list[et], ...list.slice(0, et), ...list.slice(et + 1)];
  }
  for (const e of list) {
    // Two-person sequences need a tone per person; one tone on the first would look wrong.
    const pair = cps(e.emoji).length > 1 && /holding hands|kiss|couple|handshake|family/i.test(e.name);
    if (e.skin_tone_support && !pair) toneable.push(e.emoji);
  }
  cats.push(`        Triple(${q(m[0])}, ${q(m[1])}, ${q(list.map((e) => e.emoji).join(' '))})`);
  names.push(`        ${q(list.map((e) => `${e.emoji}\t${e.name.toLowerCase()}`).join('\n'))}`);
}

const out = `// GENERATED by tools/gen-emoji.mjs from unicode-emoji-json (Emoji ${MAX_VERSION} and older). Do not edit by hand.
package com.akai.nativekb

import android.graphics.Paint

object EmojiData {
    class Category(val icon: String, val name: String, val emojis: List<String>)

    private fun e(s: String) = s.split(' ')

    /** Emoji that take a skin tone (hands, people, body parts). */
    private val toneable: Set<String> by lazy { e(${q(toneable.join(' '))}).toSet() }

    /**
     * [tone] is 0 for the default yellow, then 1 (lightest) to 5 (darkest). The tone
     * goes straight after the first character, replacing its variation selector,
     * so "🧑‍🍳" becomes "🧑🏽‍🍳".
     */
    fun withTone(emoji: String, tone: Int): String {
        if (tone !in 1..5 || emoji !in toneable) return emoji
        val first = emoji.codePointAt(0)
        var rest = Character.charCount(first)
        if (rest < emoji.length && emoji[rest] == '\\uFE0F') rest++
        return String(Character.toChars(first)) + String(Character.toChars(0x1F3FB + tone - 1)) + emoji.substring(rest)
    }

    private val raw = listOf(
${cats.join(',\n')}
    )

    /** Every category, without the emoji this phone's font can't draw (they'd show as boxes). */
    val categories: List<Category> by lazy {
        val p = Paint()
        raw.map { (icon, name, list) -> Category(icon, name, e(list).filter { p.hasGlyph(it) }) }
    }

    private val rawNames = listOf(
${names.join(',\n')}
    )

    /** The Unicode name of each emoji, in lower case ("face with tears of joy"). */
    private val names: Map<String, String> by lazy {
        val m = HashMap<String, String>(2048)
        for (block in rawNames) for (line in block.split('\\n')) {
            val tab = line.indexOf('\\t')
            if (tab > 0) m[line.substring(0, tab)] = line.substring(tab + 1)
        }
        m
    }

    fun name(emoji: String): String? = names[emoji] ?: names[emoji.replace("\\uFE0F", "")]
}
`;
fs.writeFileSync(new URL('../app/src/main/java/com/akai/nativekb/EmojiData.kt', import.meta.url), out);
console.log(`wrote EmojiData.kt: ${cats.length} categories, ${toneable.length} toneable`);
